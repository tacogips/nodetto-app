import { expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { serializeDocument } from "@nodetto/io";
import { document, element } from "../../../packages/core/src/test-helpers.ts";

test("DDL frame scope adopts contained tables and warns on straddles", () => {
  const root = mkdtempSync(join(tmpdir(), "nodetto-ddl-scope-"));
  try {
    const frame = (
      id: string,
      y: number,
      height: number,
      index: string,
      memberIds?: string[],
    ) =>
      element({
        id,
        type: "frame",
        index,
        semantic: { name: id, ...(memberIds ? { memberIds } : {}) },
        visual: { x: 0, y, width: 400, height },
      });
    const table = (id: string, y: number, index: string) =>
      element({
        id,
        type: "erd.table",
        index,
        semantic: {
          tableName: id,
          columns: [{ id: "id", name: "id", dataType: "integer" }],
        },
        visual: { x: 20, y, width: 100 },
      });
    const path = join(root, "schema.jsonl");
    const page = [{ id: "page-1", name: "Schema", kind: "erd" as const }];
    const write = (entries: ReturnType<typeof element>[]) =>
      writeFileSync(path, serializeDocument(document(entries, page)));
    const run = (...args: string[]) =>
      Bun.spawnSync([
        process.execPath,
        join(import.meta.dir, "main.ts"),
        "ddl",
        path,
        "--page",
        "Schema",
        "--dialect",
        "sqlite",
        ...args,
      ]);
    write([
      frame("zone", 0, 150, "a1"),
      table("widgets", 10, "a2"),
      table("gadgets", 130, "a3"),
      frame("catalog", -10, 300, "a4", ["zone"]),
    ]);
    const catalog = run("--frame", "catalog", "--strict");
    expect(catalog.exitCode).toBe(0);
    expect(catalog.stdout.toString()).toContain("gadgets");
    expect(catalog.stdout.toString()).toContain("widgets");
    const zone = run("--frame", "zone", "--strict");
    expect(zone.exitCode).toBe(3);
    expect(zone.stderr.toString()).toContain("gadgets");
    const relaxed = run("--frame", "zone");
    expect(relaxed.exitCode).toBe(0);
    expect(relaxed.stdout.toString()).toContain("gadgets: table excluded");
    expect(relaxed.stdout.toString()).not.toContain('CREATE TABLE "gadgets"');
    expect(relaxed.stdout.toString()).toContain('CREATE TABLE "widgets"');
    write([table("widgets", 10, "a1"), frame("late", 0, 150, "a2")]);
    const late = run("--frame", "late", "--strict");
    expect(late.exitCode).toBe(0);
    expect(late.stdout.toString()).toContain("widgets");
    const expected =
      '-- Generated by nodetto for sqlite.\n-- Review this migration before applying it to a database.\n\nPRAGMA foreign_keys = ON;\n\nCREATE TABLE "widgets" (\n  "id" INTEGER NOT NULL\n);\n';
    expect(late.stdout.toString()).toBe(expected);
    expect(run().stdout.toString()).toBe(expected);
    write([frame("below", 0, 150, "a1"), table("widgets", 10, "a2")]);
    const below = run("--frame", "below", "--strict");
    expect(below.exitCode).toBe(0);
    expect(below.stdout.toString()).toBe(expected);
    write([
      frame("a", 0, 300, "a1", ["t"]),
      frame("b", 400, 300, "a2", ["t", "o"]),
      table("t", 410, "a3"),
      table("o", 550, "a4"),
    ]);
    const duplicate = run("--frame", "b", "--strict");
    expect(duplicate.exitCode).toBe(3);
    expect(duplicate.stderr.toString()).toContain(
      "t: table excluded from frame b",
    );
    const duplicateRelaxed = run("--frame", "b");
    expect(duplicateRelaxed.exitCode).toBe(0);
    expect(duplicateRelaxed.stdout.toString()).not.toContain(
      'CREATE TABLE "t"',
    );
    expect(duplicateRelaxed.stdout.toString()).toContain('CREATE TABLE "o"');
    expect(duplicateRelaxed.stdout.toString()).toBe(
      '-- Generated by nodetto for sqlite.\n-- Review this migration before applying it to a database.\n-- Warning: t: table excluded from frame b: also listed in memberIds of frame a.\n\nPRAGMA foreign_keys = ON;\n\nCREATE TABLE "o" (\n  "id" INTEGER NOT NULL\n);\n',
    );
    write([frame("below", 0, 150, "a1"), table("widgets", 10, "a2")]);
    const pageWide = run("--strict");
    expect(pageWide.exitCode).toBe(0);
    expect(pageWide.stdout.toString()).toBe(expected);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
