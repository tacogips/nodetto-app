import { readdir, readFile, writeFile, copyFile, rename } from "node:fs/promises";
import { join } from "node:path";

const root = process.argv[2];
if (!root) throw new Error("Usage: bun scripts/vendor-lucide.ts <extracted-package-dir>");
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as { version: string };
let tags: Record<string, string[]> = {};
try { tags = JSON.parse(await readFile(join(root, "tags.json"), "utf8")); } catch (error) {
  if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
}
const allowedElements = new Set(["path", "circle", "rect", "line", "polyline", "polygon", "ellipse"]);
const attributes = ["d", "cx", "cy", "r", "x", "y", "width", "height", "rx", "ry", "x1", "y1", "x2", "y2", "points", "fill"];
const files = (await readdir(join(root, "icons"))).filter((f) => f.endsWith(".svg")).sort();
const records: [string, string[], [string, Record<string, string>][]][] = [];
for (const file of files) {
  const name = file.slice(0, -4);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) { console.warn(`Skipped invalid icon name: ${name}`); continue; }
  const svg = (await readFile(join(root, "icons", file), "utf8")).replace(/^\s*<!--[^]*?-->\s*/, "");
  const match = svg.match(/^<svg\s+([^]*?)>([^]*?)<\/svg>\s*$/);
  if (!match || !/\bviewBox="0 0 24 24"/.test(match[1])) throw new Error(`${name}: invalid SVG root`);
  const nodes: [string, Record<string, string>][] = [];
  let remaining = match[2].trim();
  while (remaining) {
    const node = remaining.match(/^<([a-z]+)\s*([^<>]*?)\s*\/\s*>/);
    if (!node || !allowedElements.has(node[1])) throw new Error(`${name}: invalid element`);
    let raw = node[2].trim();
    const attrs: Record<string, string> = {};
    while (raw) {
      const attr = raw.match(/^([a-z][a-z0-9]*)="([^"&<>]*)"(?:\s+|$)/);
      if (!attr || !attributes.includes(attr[1]) || attr[1] in attrs) throw new Error(`${name}: invalid attribute ${raw}`);
      if (attr[1] === "fill" && attr[2] !== "currentColor" && attr[2] !== "none") throw new Error(`${name}: invalid fill ${attr[2]}`);
      attrs[attr[1]] = attr[2];
      raw = raw.slice(attr[0].length);
    }
    nodes.push([node[1], Object.fromEntries(attributes.filter((a) => a in attrs).map((a) => [a, attrs[a]]))]);
    remaining = remaining.slice(node[0].length).trim();
  }
  records.push([name, tags[name] ?? [], nodes]);
}
const makeOutput = (data: typeof records, subset: boolean) => `// Generated by scripts/vendor-lucide.ts; ${subset ? "subset: first 300 names or tags matching navigation, communication, files, media, status or editing terms" : "full set"}.\nexport const LUCIDE_VERSION = ${JSON.stringify(pkg.version)};\nexport const LUCIDE_SUBSET = ${subset};\n// biome-ignore format: generated data\nexport const LUCIDE_DATA = ${JSON.stringify(JSON.stringify(data)).replace(/[\u0080-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`)};\n`;
let output = makeOutput(records, false);
if (Buffer.byteLength(output) > 1_500_000) {
  const terms = /arrow|navigation|menu|home|search|message|chat|mail|phone|file|folder|image|video|music|play|status|check|alert|edit|pen|delete|settings/i;
  output = makeOutput(records.filter(([name, iconTags]) => terms.test([name, ...iconTags].join(" "))).slice(0, 300), true);
}
await writeFile("packages/core/src/icons/lucide-data.generated.ts.tmp", output);
await rename("packages/core/src/icons/lucide-data.generated.ts.tmp", "packages/core/src/icons/lucide-data.generated.ts");
await copyFile(join(root, "LICENSE"), "packages/core/src/icons/LICENSE-lucide.txt");
